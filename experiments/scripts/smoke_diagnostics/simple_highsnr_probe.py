"""Items 2+3: a simple, higher-SNR, homogeneous-teacher/student setting.

Motivation. In the headline cell the true CIF is generated by a squared-rate DGP
    rate_j(z) = (2 z_j)^2 + (8 z_shared)^2
which is extremely heterogeneous and front-loaded (events pile up in tiny early
bins after quantile time-gridding), so per-horizon coverage fails at the FRONT.
That confounds "can the Bayesian pipeline cover at all?" with "is the DGP
pathological?".

This probe removes the confound with a clean **log-linear (proportional-hazards)
exponential competing-risk** DGP:
    log rate_j(z) = a_j + z . b_j      (moderate |b| = homogeneous, tunable SNR)
For exponential competing risks the CIF AND the discrete interval hazard have
closed forms, so we can check BIAS / MSE / COVERAGE at BOTH levels:
  - discrete hazard  lambda_j(tau_k | z) = (r_j/r_tot)(1 - exp(-r_tot * Delta_k))   [the model primitive]
  - CIF              F_j(tau_k | z)      = (r_j/r_tot)(1 - exp(-r_tot * tau_k))       [the cumulative output]
(These are mutually consistent and match competing_cif's parameterization.)

Homogeneous teacher/student: same features, same architecture (hidden dim), same
DGP; we run eta=0 (pure Bayesian survival, no teacher) and eta=1 (homogeneous
teacher) so distillation is not fighting a covariate/quality mismatch.

Sampler: warm-start SGLD with the **welling_teh** drift (validated in Exp 0 to
target the intended full-data posterior; `literal` targets an N-tempered target).

Reports, per eta: per-horizon CIF coverage/width/bias/MSE, hazard bias/MSE,
probability sanity (predicted vs true mean hazard, interval-prob sum, event rate),
R-hat/ESS. Plot: per-horizon coverage (front vs back).

Outputs (OUT_DIR, default responses_simple/): simple_highsnr_report.md, .csv, .png
"""
from __future__ import annotations

import os
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch

DEVICE = os.environ.get("DEVICE", "cuda" if torch.cuda.is_available() else "cpu")

from diskd import (
    DiSKDStudent, DiscreteSurvivalModel, WarmStartMultiChainSampler,
    competing_risk_c_index, fit_time_grid, predictive_deviance, transform_durations,
)
from diskd.uncertainty import _iter_samples, effective_sample_size, gelman_rubin_rhat

# ---------- config ----------
D = int(os.environ.get("D", 6))
J, K = 2, 12
TEACHER_N = int(os.environ.get("TEACHER_N", 5000))
STUDENT_N = int(os.environ.get("STUDENT_N", 1000))
TEST_N = int(os.environ.get("TEST_N", 1000))
HID = int(os.environ.get("HIDDEN", 32))                 # homogeneous teacher==student
BATCH = 64
TEACHER_EPOCHS = int(os.environ.get("TEACHER_EPOCHS", 100))
ADAMW_EPOCHS = int(os.environ.get("ADAMW_EPOCHS", 60))
SNR_B = float(os.environ.get("SNR_B", 0.5))             # covariate coeff magnitude (signal)
BASE_RATE = float(os.environ.get("BASE_RATE", 1.0))     # baseline cause rate
CENSOR_RATE = float(os.environ.get("CENSOR_RATE", 0.3)) # exp censoring rate (~light)
ETAS = [float(e) for e in os.environ.get("ETAS", "0,1").split(",")]
SEEDS = [int(s) for s in os.environ.get("SEEDS", "42,43,44").split(",")]
SGLD_EPOCHS = int(os.environ.get("SGLD_EPOCHS", 500))
N_CHAINS = int(os.environ.get("N_CHAINS", 5))
SAMPLES_PER_CHAIN = int(os.environ.get("SAMPLES_PER_CHAIN", 500))
EPS = float(os.environ.get("EPS", 2e-4))
DRIFT = os.environ.get("DRIFT", "welling_teh")
Z = 1.959963985
_DEFAULT = Path(__file__).resolve().parent.parent / "responses_simple"
OUT_DIR = Path(os.environ.get("OUT_DIR", str(_DEFAULT)))


# ---------- simple log-linear exponential competing-risk DGP ----------

def dgp_params(seed=0):
    rng = np.random.default_rng(1234 + seed)
    a = np.log(BASE_RATE) + np.zeros(J)
    b = SNR_B * rng.normal(size=(J, D))                 # cause-specific log-rate coeffs
    return a, b


def rates(x, a, b):
    """rate_j(z) = exp(a_j + z.b_j), shape [N,J]."""
    return np.exp(a[None, :] + x @ b.T)                 # [N,J]


def simulate(n, a, b, seed):
    rng = np.random.default_rng(seed)
    x = rng.normal(size=(n, D))
    r = rates(x, a, b)                                  # [N,J]
    r_tot = r.sum(1)
    t = rng.exponential(scale=1.0 / r)                 # [N,J] latent times
    cause = t.argmin(1)
    et = t.min(1)
    cens = rng.exponential(scale=1.0 / max(CENSOR_RATE, 1e-6), size=n)
    censored = cens < et
    dur = np.where(censored, cens, et)
    event = np.where(censored, 0, cause + 1).astype(np.int64)
    df = pd.DataFrame(x, columns=[f"x{i+1}" for i in range(D)])
    df["duration"] = dur.astype(float); df["event"] = event
    return df


def true_cif(df, cuts, a, b):
    x = df[[f"x{i+1}" for i in range(D)]].to_numpy()
    r = rates(x, a, b); r_tot = r.sum(1, keepdims=True)  # [N,1]
    share = r / r_tot                                    # [N,J]
    cuts = np.asarray(cuts)[None, :]                     # [1,K]
    overall = 1.0 - np.exp(-r_tot * cuts)               # [N,K]
    return share[:, :, None] * overall[:, None, :]      # [N,J,K]


def true_hazard(df, cuts, a, b):
    """Discrete interval hazard lambda_j(tau_k|z) = (r_j/r_tot)(1-exp(-r_tot*Delta_k))."""
    x = df[[f"x{i+1}" for i in range(D)]].to_numpy()
    r = rates(x, a, b); r_tot = r.sum(1, keepdims=True)
    share = r / r_tot
    cuts = np.asarray(cuts)
    prev = np.concatenate([[0.0], cuts[:-1]])
    delta = (cuts - prev)[None, :]                      # [1,K]
    surv_int = 1.0 - np.exp(-r_tot * delta)             # [N,K]
    return share[:, :, None] * surv_int[:, None, :]     # [N,J,K]


# ---------- fit ----------

def fit_teacher(df, tg, feats):
    return DiscreteSurvivalModel(num_risks=J, num_durations=K, hidden_dim=HID,
                                 epochs=TEACHER_EPOCHS, batch_size=BATCH, device=DEVICE,
                                 time_grid=tg).fit(df, feature_cols=feats)


def build_student(teacher, eta, optimizer, epochs):
    common = dict(num_risks=J, num_durations=K, hidden_dim=HID, epochs=epochs,
                  batch_size=BATCH, device=DEVICE, optimizer=optimizer)
    if optimizer == "sgld":
        common.update(sgld_step_size=EPS, sgld_final_step_size=EPS, sgld_gamma=0.55,
                      sgld_drift_mode=DRIFT, sgld_noise_scale=1.0, sgld_burnin_epochs=0,
                      sgld_samples_per_chain=SAMPLES_PER_CHAIN)
    if eta == 0:
        return DiscreteSurvivalModel(**common)
    return DiSKDStudent(teacher_model=teacher, teacher_type="competing", eta=eta,
                        temperature=2.0, **common)


def per_horizon_stats(cif_samples, hz_point, tcif, thz):
    """cif_samples [M,N,J,K]; returns per-horizon dicts vs truth."""
    q = np.quantile(cif_samples, [0.025, 0.5, 0.975], axis=0)      # [3,N,J,K]
    lo, med, hi = q[0], q[1], q[2]
    inside = (tcif >= lo) & (tcif <= hi)
    cov_h = inside.mean(axis=(0, 1))                              # [K]
    wid_h = (hi - lo).mean(axis=(0, 1))
    cif_bias_h = (med - tcif).mean(axis=(0, 1))
    cif_mse_h = ((med - tcif) ** 2).mean(axis=(0, 1))
    hz_bias_h = (hz_point - thz).mean(axis=(0, 1))
    hz_mse_h = ((hz_point - thz) ** 2).mean(axis=(0, 1))
    return dict(cov=cov_h, wid=wid_h, cif_bias=cif_bias_h, cif_mse=cif_mse_h,
                hz_bias=hz_bias_h, hz_mse=hz_mse_h, med=med)


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    torch.set_num_threads(int(os.environ.get("TORCH_THREADS", 4)))
    feats = [f"x{i+1}" for i in range(D)]
    print(f"=== Simple high-SNR homogeneous probe (D={D}, SNR_B={SNR_B}, drift={DRIFT}) ===")
    print(f"teacher {TEACHER_N} / student {STUDENT_N} / test {TEST_N}, hidden={HID} (homogeneous), "
          f"etas={ETAS}, seeds={SEEDS}")

    agg = {}     # (eta) -> list of per-horizon arrays across seeds
    rows = []
    for seed in SEEDS:
        a, b = dgp_params(0)                                       # SAME DGP across seeds/cohorts
        teacher_df = simulate(TEACHER_N, a, b, 10 * seed + 1)
        student_df = simulate(STUDENT_N, a, b, 10 * seed + 2)
        test_df = simulate(TEST_N, a, b, 10 * seed + 3)
        dur = np.concatenate([teacher_df["duration"].values, student_df["duration"].values])
        tg = fit_time_grid(dur, K)
        cuts = np.asarray(tg.cuts)
        tcif = true_cif(test_df, cuts, a, b)
        thz = true_hazard(test_df, cuts, a, b)
        teacher = fit_teacher(teacher_df, tg, feats)

        tdur, tev = test_df["duration"].to_numpy(), test_df["event"].to_numpy()
        tidx = transform_durations(tdur, tg)
        for eta in ETAS:
            t0 = time.time()
            torch.manual_seed(1000 * seed); np.random.seed(1000 * seed)
            adam = build_student(teacher, eta, "adamw", ADAMW_EPOCHS)
            adam.time_grid = tg
            adam.fit(student_df, feature_cols=feats)
            pretrained = {k: v.clone() for k, v in adam.net.state_dict().items()}
            adam_hz = np.asarray(adam.predict_hazard(test_df))
            adam_cif = np.asarray(adam.predict_cif(test_df))

            base = build_student(teacher, eta, "sgld", SGLD_EPOCHS); base.time_grid = tg
            sampler = WarmStartMultiChainSampler(base, pretrained, n_chains=N_CHAINS,
                                                 seeds=[100 * seed + c for c in range(N_CHAINS)])
            sampler.fit(student_df, feature_cols=feats)
            lead = sampler.lead_chain
            cifs, hzs, chain_fn = [], [], []
            for chain in sampler.chains:
                ch_cif = []
                for _, m in _iter_samples(lead, chain.posterior_samples):
                    c = np.asarray(m.predict_cif(test_df)); cifs.append(c); ch_cif.append(c)
                    hzs.append(np.asarray(m.predict_hazard(test_df)))
                chain_fn.append(np.stack(ch_cif)[:, :, 0, -1].mean(1))   # cohort-mean CIF c1 last horizon
            cifs = np.stack(cifs); hzs = np.stack(hzs)
            hz_point = hzs.mean(0)                                       # posterior-mean hazard
            st = per_horizon_stats(cifs, hz_point, tcif, thz)
            # R-hat/ESS on the cohort-mean functional
            fn = np.stack(chain_fn)
            try: rhat = float(gelman_rubin_rhat(fn)); ess = float(effective_sample_size(fn))
            except Exception: rhat, ess = float("nan"), float("nan")
            ctd = competing_risk_c_index(st["med"], tdur, tev)
            dev = float(np.mean([predictive_deviance(
                np.asarray(m.predict_interval_probs(test_df)), tidx, tev)
                for _, m in _iter_samples(lead, sampler.chains[0].posterior_samples)]))
            # probability sanity
            ip = np.asarray(adam.predict_interval_probs(test_df))        # [N,J+1,K]
            prob_sum = float(ip.sum(1).mean())
            agg.setdefault(eta, []).append(st)
            rows.append(dict(seed=seed, eta=eta, cov=float(st["cov"].mean()),
                             front_cov=float(st["cov"][:3].mean()), back_cov=float(st["cov"][9:].mean()),
                             wid=float(st["wid"].mean()), cif_mse=float(st["cif_mse"].mean()),
                             hz_mse=float(st["hz_mse"].mean()), hz_bias=float(np.abs(st["hz_bias"]).mean()),
                             ctd1=float(ctd[0]), dev=dev, rhat=rhat, ess=ess,
                             adam_hz_mse=float(((adam_hz - thz) ** 2).mean()),
                             prob_sum=prob_sum))
            print(f"  seed{seed} eta={eta}: cov={st['cov'].mean():.3f} "
                  f"(front={st['cov'][:3].mean():.3f} back={st['cov'][9:].mean():.3f}) "
                  f"wid={st['wid'].mean():.3f} cif_mse={st['cif_mse'].mean():.2e} "
                  f"hz_mse={st['hz_mse'].mean():.2e} Ctd1={ctd[0]:.3f} Rhat={rhat:.2f} "
                  f"prob_sum={prob_sum:.3f} ({time.time()-t0:.0f}s)", flush=True)

    # ---- aggregate + plot per-horizon ----
    df = pd.DataFrame(rows); df.to_csv(OUT_DIR / "simple_highsnr.csv", index=False)
    x = np.arange(1, K + 1)
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.2))
    cols = {0: "#888", 1: "#1f77b4"}
    for eta in ETAS:
        cov = np.stack([s["cov"] for s in agg[eta]]).mean(0)
        wid = np.stack([s["wid"] for s in agg[eta]]).mean(0)
        hzm = np.stack([s["hz_mse"] for s in agg[eta]]).mean(0)
        ax[0].plot(x, cov, "o-", color=cols.get(eta, "C2"), label=f"eta={eta:g}")
        ax[1].plot(x, wid, "o-", color=cols.get(eta, "C2"), label=f"eta={eta:g}")
        ax[2].plot(x, hzm, "o-", color=cols.get(eta, "C2"), label=f"eta={eta:g}")
    ax[0].axhline(0.95, ls="--", c="gray", lw=.8); ax[0].set_ylim(0, 1.02)
    ax[0].set_title("CIF coverage vs horizon"); ax[1].set_title("CIF interval width vs horizon")
    ax[2].set_title("hazard MSE vs horizon")
    for a_ in ax: a_.set_xlabel("horizon"); a_.grid(ls=":", alpha=.4); a_.legend(fontsize=8)
    fig.suptitle(f"Simple high-SNR homogeneous setting (D={D}, SNR_B={SNR_B}, {DRIFT} SGLD)", fontsize=12)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(OUT_DIR / "simple_highsnr_per_horizon.png", dpi=140, bbox_inches="tight")

    ag = df.groupby("eta").mean(numeric_only=True).reset_index()
    md = ["# Simple / high-SNR / homogeneous probe (items 2+3)", ""]
    md.append(f"Log-linear exponential competing-risk DGP: log rate_j(z) = a_j + z.b_j, D={D}, "
              f"SNR_B={SNR_B}, base_rate={BASE_RATE}, censor_rate={CENSOR_RATE}. Teacher {TEACHER_N} / "
              f"student {STUDENT_N} / test {TEST_N}, hidden={HID} (homogeneous), {DRIFT} SGLD "
              f"({N_CHAINS}x{SAMPLES_PER_CHAIN}, eps={EPS:.0e}). Seeds {SEEDS}. Truth = closed form "
              f"(CIF and discrete hazard). Nominal 0.95.")
    md.append("")
    md.append("| eta | cov | front cov | back cov | width | CIF MSE | hazard MSE | |hz bias| | Ctd1 | Dev | R-hat | prob_sum |")
    md.append("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for _, r in ag.iterrows():
        md.append(f"| {r['eta']:g} | {r['cov']:.3f} | {r['front_cov']:.3f} | {r['back_cov']:.3f} | "
                  f"{r['wid']:.3f} | {r['cif_mse']:.2e} | {r['hz_mse']:.2e} | {r['hz_bias']:.2e} | "
                  f"{r['ctd1']:.3f} | {r['dev']:.3f} | {r['rhat']:.2f} | {r['prob_sum']:.3f} |")
    md.append("")
    md.append("`prob_sum` should be 1.0 (interval probs incl. no-event sum to 1). `front cov` = t1-t3, "
              "`back cov` = t10-t12. Hazard MSE/bias are at the discrete-hazard level (the model "
              "primitive), separate from CIF (the cumulative output).")
    md.append("")
    md.append("![per-horizon](simple_highsnr_per_horizon.png)")
    md.append("")
    md.append("Raw rows: `simple_highsnr.csv`.")
    (OUT_DIR / "simple_highsnr_report.md").write_text("\n".join(md) + "\n")
    print(f"\nSaved to {OUT_DIR}", flush=True)


if __name__ == "__main__":
    main()
